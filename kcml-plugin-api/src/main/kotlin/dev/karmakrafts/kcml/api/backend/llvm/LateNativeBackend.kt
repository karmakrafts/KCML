package dev.karmakrafts.kcml.api.backend.llvm

import dev.karmakrafts.kcml.api.backend.Backend
import dev.karmakrafts.kcml.api.backend.BackendType
import dev.karmakrafts.kcml.api.target.NativeCompileTarget
import kotlinx.cinterop.ExperimentalForeignApi
import llvm.LLVMContextRef
import llvm.LLVMModuleRef
import org.jetbrains.kotlin.backend.konan.NativeCompilationConfig
import org.jetbrains.kotlin.backend.konan.NativeSecondStageCompilationConfig
import org.jetbrains.kotlin.backend.konan.driver.NativePhaseContext
import org.jetbrains.kotlin.backend.konan.ir.BackendNativeSymbols
import org.jetbrains.kotlin.config.CompilerConfiguration
import org.jetbrains.kotlin.ir.IrBuiltIns

/**
 * Exposes Kotlin/Native backend state to KCML extensions.
 *
 * In addition to the common IR services, this context provides the Konan compilation state and
 * LLVM objects used while Kotlin/Native lowers IR to native code.
 */
@OptIn(ExperimentalForeignApi::class)
public interface LateNativeBackend : Backend {
    /** Identifies this context as the late Kotlin/Native backend. */
    override val type: BackendType
        get() = BackendType.LateNative

    /** Native compilation target processed during LLVM code generation. */
    override val compileTarget: NativeCompileTarget

    /** Built-in IR definitions provided by Kotlin. */
    public val irBuiltIns: IrBuiltIns

    /** Kotlin/Native backend symbols resolved for the active compilation. */
    public val symbols: BackendNativeSymbols

    /** Native compiler phase context that owns the current backend state. */
    public val phaseContext: NativePhaseContext

    /** Configuration for Kotlin/Native's second-stage compilation pipeline. */
    public val secondStageConfig: NativeSecondStageCompilationConfig

    /** LLVM context receiving native code generated by the Kotlin/Native backend. */
    public val llvmContext: LLVMContextRef

    /** LLVM module produced for the compilation currently being lowered. */
    public val llvmModule: LLVMModuleRef

    /** Native compilation configuration obtained from [phaseContext]. */
    public val nativeConfig: NativeCompilationConfig
        get() = phaseContext.config

    /** Kotlin compiler configuration used by the native compilation. */
    override val config: CompilerConfiguration
        get() = nativeConfig.configuration
}